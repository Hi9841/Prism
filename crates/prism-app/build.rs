//! Embeds the Prism icon and the version resource. The application manifest
//! (Common Controls v6 for prism-core's TaskDialogIndirect and
//! SetWindowSubclass, PerMonitorV2 DPI) comes from gpui's default
//! `windows-manifest` feature.
//!
//! The version resource carries the same strings as the Tauri build (the
//! release script compares `ProductVersion` with the release version).

use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=resources/icon.ico");
    // Test channels build other versions (packaging/build-installer.ps1).
    println!("cargo:rerun-if-env-changed=PRISM_VERSION_OVERRIDE");
    let version = std::env::var("PRISM_VERSION_OVERRIDE")
        .ok()
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| std::env::var("CARGO_PKG_VERSION").expect("CARGO_PKG_VERSION"));
    println!("cargo:rustc-env=PRISM_VERSION={version}");
    let mut parts = version.split(['.', '-', '+']).map(|part| part.parse::<u16>().unwrap_or(0));
    let numeric = [0; 4].map(|_: u16| parts.next().unwrap_or(0));
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let icon = manifest_dir.join("resources").join("icon.ico");
    let rc = format!(
        r#"// Generated by build.rs from the crate version.
IDI_APPLICATION_ICON ICON "{icon}"

1 VERSIONINFO
FILEVERSION {a},{b},{c},{d}
PRODUCTVERSION {a},{b},{c},{d}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "Prism"
            VALUE "FileDescription", "Prism"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "prism"
            VALUE "OriginalFilename", "prism.exe"
            VALUE "ProductName", "Prism"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#,
        icon = icon.display().to_string().replace('\\', "\\\\"),
        a = numeric[0],
        b = numeric[1],
        c = numeric[2],
        d = numeric[3],
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("prism.rc");
    std::fs::write(&out, rc).expect("write the resource script");
    let _ = embed_resource::compile(&out, embed_resource::NONE);
}
