#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct AppEntry {
    /// Friendly display name shown in the UI and matched first.
    pub name: String,
    /// Lowercased, punctuation-stripped name for exact matching.
    pub normalized_name: String,
    /// Stable unique id: the AUMID when present, else "target|arguments".
    pub app_id: String,
    /// Data-URL of the app's real icon (PNG), when it resolves.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub icon: Option<String>,
    /// Resolved launch target (exe path or web URL).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    /// Launch arguments (shortcut arguments), when present.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub args: Option<String>,
    /// Working directory from the shortcut, when set.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub working_directory: Option<String>,
    /// Original shortcut location (.lnk/.url path), when present.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub location: Option<String>,
    /// AppUserModelID for packaged apps, when available.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub aumid: Option<String>,
    /// Where the entry came from (startMenu/desktop/documents/profile/
    /// taskbar/appsFolder/registry/appPaths/applications/programs/shell-file).
    pub source: String,
    /// Searchable aliases: exe names, folder names, publisher, description.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub keywords: Vec<String>,
}

pub struct AppIndex {
    pub apps: Vec<AppEntry>,
    pub scanned_at: SystemTime,
}

/// Returns the cached scan when it is younger than [`CACHE_TTL`] and no
/// install location has changed since that scan.
pub fn scan(cache_path: &Path) -> Result<AppIndex, String> {
    if cache_fresh(cache_path).unwrap_or(false) {
        if let Some(index) = read_cached_index(cache_path) {
            // A shortcut created after the cache file was written must not
            // wait out the TTL. Desktop and Start Menu updates are the signal.
            // An app updated in place must not keep its old icon either.
            if !installs_changed_since(index.scanned_at)
                && !apps_updated_since(&watched_files(&index.apps), index.scanned_at)
            {
                return Ok(index);
            }
        }
    }
    scan_force(cache_path)
}

fn cache_fresh(path: &Path) -> Result<bool, String> {
    let meta = std::fs::metadata(path).map_err(|e| e.to_string())?;
    let age = SystemTime::now()
        .duration_since(meta.modified().map_err(|e| e.to_string())?)
        .unwrap_or_default();
    Ok(age < CACHE_TTL)
}

fn read_cached_index(path: &Path) -> Option<AppIndex> {
    let text = std::fs::read_to_string(path).ok()?;
    let mut value: serde_json::Value = serde_json::from_str(&text).ok()?;
    if value.get("version").and_then(|v| v.as_u64()) != Some(APPS_CACHE_VERSION as u64) {
        return None;
    }
    // Caches written before `scannedAt` existed still carry a usable clock:
    // the file mtime is when that scan finished.
    let scanned_at = value
        .get("scannedAt")
        .and_then(|v| v.as_u64())
        .map(millis_to_system)
        .or_else(|| file_mtime(path))?;
    let apps = value
        .get_mut("apps")
        .and_then(|apps| serde_json::from_value(std::mem::take(apps)).ok())?;
    Some(AppIndex { apps, scanned_at })
}

fn write_cache(path: &Path, apps: &[AppEntry], scanned_at: SystemTime) {
    let value = serde_json::json!({
        "version": APPS_CACHE_VERSION,
        "scannedAt": system_millis(scanned_at),
        "apps": apps,
    });
    let text = serde_json::to_string(&value).unwrap_or_default();
    let _ = std::fs::create_dir_all(path.parent().unwrap_or(Path::new("")));
    // Atomic commit (temp file + replace) so a crash mid-write can never
    // corrupt the cache and force a full rescan.
    let temp = path.with_extension("json.tmp");
    if std::fs::write(&temp, text).is_ok() {
        let _ = crate::files::replace_file(&temp, path);
    }
}

/// Always rescans (used by the manual refresh button).
pub fn scan_force(cache_path: &Path) -> Result<AppIndex, String> {
    // Stamp the start, not the finish, so a shortcut created while the walk
    // is in progress stays newer than this index and is picked up next open.
    let scanned_at = SystemTime::now();
    let apps = scan_raw()?;
    write_cache(cache_path, &apps, scanned_at);
    Ok(AppIndex { apps, scanned_at })
}

fn system_millis(time: SystemTime) -> u64 {
    time.duration_since(SystemTime::UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

fn millis_to_system(millis: u64) -> SystemTime {
    SystemTime::UNIX_EPOCH + Duration::from_millis(millis)
}

fn file_mtime(path: &Path) -> Option<SystemTime> {
    std::fs::metadata(path)
        .and_then(|meta| meta.modified())
        .ok()
}

/// True when a Desktop/Start Menu shortcut or an install folder was written
/// after `since`. A running session uses this to notice apps installed after
/// the in-memory index was built.
pub fn installs_changed_since(since: SystemTime) -> bool {
    for root in install_watch_roots() {
        let changed = match root.kind {
            WatchKind::Shortcuts { depth } => shortcuts_changed(&root.path, since, depth),
            // Product folders are compared one level deep. A file written inside
            // an already-indexed install (Zeron rewrites its own folder on
            // launch) must not force a full rescan; adding or removing a
            // product directory updates the parent.
            WatchKind::Products => mtime_after(&root.path, since),
        };
        if changed {
            return true;
        }
    }
    false
}

struct InstallRoot {
    path: PathBuf,
    kind: WatchKind,
}

enum WatchKind {
    /// `.lnk` / `.url` files. `depth` is how many child directories to enter
    /// when that directory itself is newer than the last scan.
    Shortcuts { depth: u32 },
    /// Install roots. Only the root directory mtime counts: adding or
    /// removing a product folder updates it, and writes inside a product do not.
    Products,
}

fn install_watch_roots() -> Vec<InstallRoot> {
    let mut roots = Vec::new();
    for (fid, depth) in [
        (FOLDERID_Programs, 4u32),
        (FOLDERID_CommonPrograms, 4u32),
        (FOLDERID_Desktop, 3u32),
        (FOLDERID_PublicDesktop, 3u32),
    ] {
        if let Some(path) = unsafe { known_folder(&fid) } {
            roots.push(InstallRoot {
                path,
                kind: WatchKind::Shortcuts { depth },
            });
        }
    }
    if let Some(profile) = unsafe { known_folder(&FOLDERID_Profile) } {
        let taskbar = profile
            .join("AppData")
            .join("Roaming")
            .join("Microsoft")
            .join("Internet Explorer")
            .join("Quick Launch")
            .join("User Pinned")
            .join("TaskBar");
        roots.push(InstallRoot {
            path: taskbar,
            kind: WatchKind::Shortcuts { depth: 1 },
        });
    }
    for fid in [FOLDERID_ProgramFiles, FOLDERID_ProgramFilesX86] {
        if let Some(path) = unsafe { known_folder(&fid) } {
            roots.push(InstallRoot {
                path,
                kind: WatchKind::Products,
            });
        }
    }
    if let Some(local) = unsafe { known_folder(&FOLDERID_LocalAppData) } {
        roots.push(InstallRoot {
            path: local.join("Programs"),
            kind: WatchKind::Products,
        });
    }
    roots
}

/// A shortcut change is a `.lnk` or `.url` newer than `since`. Other files
/// (a document dropped on the Desktop) do not invalidate the app index.
/// Child directories are entered only when their own mtime moved, which is
/// what creating a shortcut inside them does.
fn shortcuts_changed(dir: &Path, since: SystemTime, depth: u32) -> bool {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return false;
    };
    for entry in entries.flatten() {
        let Ok(meta) = entry.metadata() else {
            continue;
        };
        let Ok(modified) = meta.modified() else {
            continue;
        };
        if meta.is_dir() {
            if depth > 0 && modified > since && shortcuts_changed(&entry.path(), since, depth - 1) {
                return true;
            }
            continue;
        }
        if modified <= since {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_lowercase();
        if name.ends_with(".lnk") || name.ends_with(".url") {
            return true;
        }
    }
    false
}

fn mtime_after(path: &Path, since: SystemTime) -> bool {
    std::fs::metadata(path)
        .and_then(|meta| meta.modified())
        .ok()
        .is_some_and(|modified| modified > since)
}

fn scan_raw() -> Result<Vec<AppEntry>, String> {
    let _com = ComGuard::init();
    let mut ctx = ScanCtx::new();
    ctx.scan_shortcut_roots();
    ctx.scan_apps_folder();
    ctx.scan_registry();
    ctx.scan_registered_apps();
    ctx.scan_program_files();
    ctx.icons.prune();
    ctx.apps.sort_by_cached_key(|app| app.name.to_lowercase());
    Ok(ctx.apps)
}

/* ---------------- shared scanning context ---------------- */

struct ScanCtx {
    icons: IconCache,
    packages: PackageVersions,
    /// Canonical keys: AUMID, or lowercase "target|args". First scan wins.
    seen: HashMap<String, ()>,
    apps: Vec<AppEntry>,
}

impl ScanCtx {
    fn new() -> Self {
        Self {
            icons: IconCache::new(icon_cache_dir()),
            packages: PackageVersions::load(),
            seen: HashMap::new(),
            apps: Vec::new(),
        }
    }

    /// Adds an entry unless an identical app was already indexed.
    fn push(&mut self, entry: AppEntry) {
        if self.seen.insert(entry.app_id.clone(), ()).is_some() {
            return;
        }
        let mut entry = entry;
        entry.keywords = dedupe_keywords(entry.keywords);
        self.apps.push(entry);
    }
}

struct ComGuard {
    initialized: bool,
}

impl ComGuard {
    fn init() -> Self {
        Self {
            initialized: unsafe { CoInitializeEx(None, COINIT_APARTMENTTHREADED) }.is_ok(),
        }
    }
}

impl Drop for ComGuard {
    fn drop(&mut self) {
        // CoUninitialize must only balance a successful CoInitializeEx call.
        // In particular, RPC_E_CHANGED_MODE means this thread already belongs
        // to a different apartment and must be left untouched.
        if self.initialized {
            unsafe { CoUninitialize() }
        }
    }
}

/* ---------------- shortcut sources (Start Menu / Desktop / Documents / profile) ---------------- */

impl ScanCtx {
    fn scan_shortcut_roots(&mut self) {
        for (fid, source, depth, cap) in [
            (FOLDERID_Programs, "startMenu", 4u32, 2000usize),
            (FOLDERID_CommonPrograms, "startMenu", 4, 2000),
            (FOLDERID_Desktop, "desktop", 3, 800),
            (FOLDERID_PublicDesktop, "desktop", 3, 400),
            (FOLDERID_Documents, "documents", 3, 800),
            (FOLDERID_PublicDocuments, "documents", 3, 400),
            (FOLDERID_Profile, "profile", 1, 100),
        ] {
            if let Some(dir) = unsafe { known_folder(&fid) } {
                self.scan_shortcut_dir(&dir, source, depth, cap);
            }
        }
        // Taskbar pins and the classic Quick Launch area live under the
        // profile's AppData; both are small, curated shortcut stores.
        if let Some(profile) = unsafe { known_folder(&FOLDERID_Profile) } {
            let quick = profile
                .join("AppData")
                .join("Roaming")
                .join("Microsoft")
                .join("Internet Explorer")
                .join("Quick Launch");
            let taskbar = quick.join("User Pinned").join("TaskBar");
            self.scan_shortcut_dir(&quick, "taskbar", 1, 100);
            self.scan_shortcut_dir(&taskbar, "taskbar", 1, 100);
        }
    }

    fn scan_shortcut_dir(&mut self, root: &Path, source: &str, max_depth: u32, max_files: usize) {
        self.walk_shortcuts(root, source, max_depth, max_files, 0, &mut 0);
    }

    fn walk_shortcuts(
        &mut self,
        dir: &Path,
        source: &str,
        max_depth: u32,
        max_files: usize,
        depth: u32,
        count: &mut usize,
    ) {
        if depth > max_depth || *count >= max_files {
            return;
        }
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            if *count >= max_files {
                return;
            }
            let Ok(file_type) = entry.file_type() else {
                continue;
            };
            let Some(name) = entry.file_name().to_str().map(str::to_owned) else {
                continue;
            };
            if file_type.is_dir() {
                if SKIP_DIRS.contains(&name.as_str()) {
                    continue;
                }
                self.walk_shortcuts(
                    &entry.path(),
                    source,
                    max_depth,
                    max_files,
                    depth + 1,
                    count,
                );
            } else if file_type.is_file() {
                let lower = name.to_lowercase();
                if lower.ends_with(".lnk") {
                    *count += 1;
                    self.index_lnk(&entry.path(), source);
                } else if lower.ends_with(".url") {
                    *count += 1;
                    self.index_url(&entry.path(), source);
                } else if lower.ends_with(".msc") || lower.ends_with(".cpl") {
                    *count += 1;
                    self.index_shell_file(&entry.path(), source);
                }
            }
        }
    }

    fn index_lnk(&mut self, path: &Path, source: &str) {
        let Some(resolved) = resolve_lnk(path) else {
            return;
        };
        let aumid = read_lnk_aumid(path);
        let key = match &aumid {
            Some(a) => a.clone(),
            None => format!("{}|{}", resolved.target, resolved.args).to_lowercase(),
        };
        if self.seen.contains_key(&key) {
            return;
        }
        // Broken/dead shortcut: virtual targets (UWP AppsFolder links,
        // shell:/::{CLSID} targets) can't be stat-checked, everything else
        // must resolve to a file that exists on disk.
        let target_missing = resolved.target.is_empty()
            || (!looks_virtual(&resolved.target) && !Path::new(&resolved.target).exists());
        if aumid.is_none() && target_missing {
            return;
        }
        let name = path
            .file_stem()
            .map(|s| clean_name(&s.to_string_lossy()))
            .unwrap_or_default();
        if name.is_empty() {
            return;
        }
        let mut keywords = Vec::new();
        if let Some(stem) = Path::new(&resolved.target).file_stem() {
            keywords.push(stem.to_string_lossy().into_owned());
        }
        // Virtual shortcuts carry the app identity in their AUMID.
        if resolved.target.is_empty() {
            if let Some((package, app_id)) = aumid.as_deref().and_then(|a| a.split_once('!')) {
                keywords.push(package.to_string());
                keywords.push(app_id.to_string());
            }
        }
        if let Some(parent) = path.parent().and_then(|p| p.file_name()) {
            keywords.push(parent.to_string_lossy().into_owned());
        }
        if !resolved.description.is_empty() {
            keywords.push(resolved.description);
        }
        self.push(AppEntry {
            name: name.clone(),
            normalized_name: normalize(&name),
            app_id: key,
            // The shell resolves the shortcut's own (custom) icon. An update
            // can replace the target or icon file and keep the shortcut.
            icon: self.icons.get_for(
                &path.to_string_lossy(),
                &[&resolved.target, &resolved.icon_location],
                aumid
                    .as_deref()
                    .map_or("", |aumid| self.packages.version(aumid)),
            ),
            path: (!resolved.target.is_empty()).then_some(resolved.target),
            args: (!resolved.args.is_empty()).then_some(resolved.args),
            working_directory: (!resolved.working_directory.is_empty())
                .then_some(resolved.working_directory),
            location: Some(path.to_string_lossy().into_owned()),
            aumid,
            source: source.to_string(),
            keywords,
        });
    }

    fn index_shell_file(&mut self, path: &Path, source: &str) {
        let key = format!("shell|{}", path.to_string_lossy().to_lowercase());
        if self.seen.contains_key(&key) {
            return;
        }
        let name = path
            .file_stem()
            .map(|value| clean_name(&value.to_string_lossy()))
            .unwrap_or_default();
        if name.is_empty() {
            return;
        }
        let extension = path
            .extension()
            .and_then(|value| value.to_str())
            .unwrap_or_default()
            .to_ascii_lowercase();
        self.push(AppEntry {
            name: name.clone(),
            normalized_name: normalize(&name),
            app_id: key,
            icon: self.icons.get(&path.to_string_lossy()),
            path: Some(path.to_string_lossy().into_owned()),
            args: None,
            working_directory: None,
            location: Some(path.to_string_lossy().into_owned()),
            aumid: None,
            source: source.to_string(),
            keywords: vec![extension],
        });
    }

    fn index_url(&mut self, path: &Path, source: &str) {
        let Ok(text) = std::fs::read_to_string(path) else {
            return;
        };
        let mut url = None;
        let mut icon_file = None;
        for line in text.lines() {
            let line = line.trim();
            if let Some(value) = line.strip_prefix("URL=") {
                url = Some(value);
            } else if let Some(value) = line.strip_prefix("IconFile=") {
                icon_file = Some(value);
            }
        }
        // Accept any registered scheme (http(s), steam://, game launcher
        // protocols...); the shell resolves the handler on launch.
        let Some(url) = url else {
            return;
        };
        if !url.contains("://") {
            return;
        }
        let key = format!("url|{}", url.to_lowercase());
        if self.seen.contains_key(&key) {
            return;
        }
        let name = path
            .file_stem()
            .map(|s| clean_name(&s.to_string_lossy()))
            .unwrap_or_default();
        if name.is_empty() {
            return;
        }
        // Prefer the .url's explicit IconFile (real game/app icons), falling
        // back to the shell icon for the .url file itself.
        let icon_file = icon_file.map(|f| expand_env(f).trim().to_string());
        let icon = match icon_file {
            Some(file) if !file.is_empty() && Path::new(&file).exists() => self.icons.get(&file),
            _ => self.icons.get(&path.to_string_lossy()),
        };
        let host = url.split("://").next().unwrap_or("").to_lowercase();
        let mut keywords = vec![host];
        if let Some(rest) = url.split("://").nth(1) {
            if let Some(domain) = rest.split('/').next() {
                if !domain.is_empty() {
                    keywords.push(domain.to_lowercase());
                }
            }
        }
        self.push(AppEntry {
            name: name.clone(),
            normalized_name: normalize(&name),
            app_id: key,
            icon,
            path: Some(url.to_string()),
            args: None,
            working_directory: None,
            location: Some(path.to_string_lossy().into_owned()),
            aumid: None,
            source: source.to_string(),
            keywords,
        });
    }
}

/// Resolved IShellLink state for a single .lnk file.
struct ResolvedLnk {
    target: String,
    args: String,
    working_directory: String,
    description: String,
    /// The shortcut's own icon file, environment variables expanded. Empty
    /// when the icon comes from the target.
    icon_location: String,
}

/// Resolves a shortcut through the Windows Shell COM APIs
/// (IShellLink + IPersistFile), returning its real target, arguments,
/// working directory and description. Returns None for unreadable links.
fn resolve_lnk(path: &Path) -> Option<ResolvedLnk> {
    unsafe {
        let link: IShellLinkW =
            CoCreateInstance(&CLSID_SHELL_LINK, None, CLSCTX_INPROC_SERVER).ok()?;
        let persist: IPersistFile = link.cast().ok()?;
        let wide_path = wide(&path.to_string_lossy());
        persist.Load(PCWSTR(wide_path.as_ptr()), STGM_READ).ok()?;

        // Resolve the target through the shortcut's IDList; this also
        // expands environment variables and follows special folders. Virtual
        // shortcuts (UWP apps) resolve to no filesystem path - the caller
        // detects those via the AUMID and keeps the link itself.
        let target = {
            let pidl = link.GetIDList().ok()?;
            let mut buffer = [0u16; 260];
            let path = if SHGetPathFromIDListW(pidl, &mut buffer).as_bool() {
                wide_trim(&buffer)
            } else {
                String::new()
            };
            CoTaskMemFree(Some(pidl as *const c_void));
            path
        };
        let args = read_buf16(|buf| link.GetArguments(buf));
        let working_directory = read_buf16(|buf| link.GetWorkingDirectory(buf));
        let description = read_buf16(|buf| link.GetDescription(buf));
        let mut icon_index = 0;
        let icon_location = expand_env(&read_buf16(|buf| {
            link.GetIconLocation(buf, &mut icon_index)
        }));
        Some(ResolvedLnk {
            target,
            args,
            working_directory,
            description,
            icon_location,
        })
    }
}

/// Reads System.AppUserModel.ID off a .lnk file so Store/UWP shortcuts are
/// keyed (and launched) by their AUMID.
fn read_lnk_aumid(path: &Path) -> Option<String> {
    unsafe {
        let wide_path = wide(&path.to_string_lossy());
        let store: IPropertyStore =
            SHCreateItemFromParsingName(PCWSTR(wide_path.as_ptr()), None).ok()?;
        let mut value = store.GetValue(&PKEY_AppUserModel_ID).ok()?;
        let result = prop_lpwstr(&value);
        let _ = PropVariantClear(&mut value);
        result
    }
}

/* ---------------- shell:AppsFolder (packaged / Store apps) ---------------- */

impl ScanCtx {
    fn scan_apps_folder(&mut self) {
        unsafe {
            let item: IShellItem =
                match SHCreateItemFromParsingName(PCWSTR(w!("shell:AppsFolder").as_ptr()), None) {
                    Ok(item) => item,
                    Err(_) => return,
                };
            let folder: IShellFolder = match item.BindToHandler(None, &BHID_SFObject) {
                Ok(folder) => folder,
                Err(_) => return,
            };
            let mut enumerator: Option<IEnumIDList> = None;
            let hr = folder.EnumObjects(
                HWND(std::ptr::null_mut()),
                SHCONTF_NONFOLDERS.0 as u32 | SHCONTF_INCLUDEHIDDEN.0 as u32,
                &mut enumerator,
            );
            if !hr.is_ok() {
                return;
            }
            let Some(enumerator) = enumerator else {
                return;
            };
            // Enumeration yields *child* PIDLs; an absolute parent PIDL is
            // needed to build shell items for them.
            let Ok(parent_pidl) = SHGetIDListFromObject(&folder) else {
                return;
            };
            loop {
                let mut pidls: [*mut ITEMIDLIST; 1] = [std::ptr::null_mut()];
                let hr = enumerator.Next(&mut pidls, None);
                let pidl = pidls[0];
                if pidl.is_null() || !hr.is_ok() {
                    break;
                }
                self.index_apps_folder_item(&folder, parent_pidl, pidl);
                ILFree(Some(pidl));
            }
            ILFree(Some(parent_pidl));
        }
    }

    fn index_apps_folder_item(
        &mut self,
        folder: &IShellFolder,
        parent_pidl: *const ITEMIDLIST,
        pidl: *mut ITEMIDLIST,
    ) {
        unsafe {
            // Build the real shell item for the child so display name and
            // property store resolve correctly.
            let Ok(item) =
                SHCreateItemWithParent(Some(parent_pidl), folder, pidl).map(|i: IShellItem| i)
            else {
                return;
            };
            let Ok(name_ptr) = item.GetDisplayName(SIGDN_NORMALDISPLAY) else {
                return;
            };
            let name = name_ptr.to_string().unwrap_or_default();
            CoTaskMemFree(Some(name_ptr.as_ptr() as *const c_void));
            let name = name.trim().to_string();
            if name.is_empty() {
                return;
            }
            let Ok(store) = item.BindToHandler::<_, IPropertyStore>(None, &BHID_PropertyStore)
            else {
                return;
            };
            let Ok(mut value) = store.GetValue(&PKEY_AppUserModel_ID) else {
                return;
            };
            let aumid = prop_lpwstr(&value);
            let _ = PropVariantClear(&mut value);
            let Some(aumid) = aumid else {
                return;
            };
            if aumid.is_empty() {
                return;
            }
            let mut keywords = Vec::new();
            if let Some((package, app_id)) = aumid.split_once('!') {
                keywords.push(package.to_string());
                keywords.push(app_id.to_string());
            }
            // Desktop apps surface in AppsFolder with a {GUID}\relative
            // AppID. Resolve those to real paths so they dedupe against
            // shortcuts/registry entries and launch directly.
            if aumid.starts_with('{') {
                let Some(path) = resolve_guid_appid(&aumid) else {
                    return;
                };
                let key = path.to_lowercase();
                if self.seen.contains_key(&key) {
                    return;
                }
                let mut exe_keywords = Vec::new();
                if let Some(stem) = Path::new(&path).file_stem() {
                    exe_keywords.push(stem.to_string_lossy().into_owned());
                }
                self.push(AppEntry {
                    name: name.clone(),
                    normalized_name: normalize(&name),
                    app_id: key,
                    icon: self.icons.get(&path),
                    path: Some(path),
                    args: None,
                    working_directory: None,
                    location: None,
                    aumid: None,
                    source: "appsFolder".to_string(),
                    keywords: exe_keywords,
                });
                return;
            }
            if self.seen.contains_key(&aumid) {
                return;
            }
            self.push(AppEntry {
                name: name.clone(),
                normalized_name: normalize(&name),
                app_id: aumid.clone(),
                // A package update installs a new package version.
                icon: self.icons.get_with(
                    &format!("apps-folder-v2|{aumid}|{}", self.packages.version(&aumid)),
                    || extract_apps_folder_icon(&item, folder, pidl),
                ),
                path: None,
                args: None,
                working_directory: None,
                location: None,
                aumid: Some(aumid),
                source: "appsFolder".to_string(),
                keywords,
            });
        }
    }
}

/// Resolves `{KNOWN_FOLDER_GUID}\relative\path` AppIDs (what Get-StartApps
/// reports for desktop apps) to a real file path.
fn resolve_guid_appid(app_id: &str) -> Option<String> {
    let (guid, relative) = app_id.split_once('\\')?;
    let mut candidates: Vec<PathBuf> = Vec::new();
    if guid.eq_ignore_ascii_case("{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}") {
        if let Some(root) = std::env::var_os("SystemRoot") {
            candidates.push(PathBuf::from(root).join("System32").join(relative));
        }
    } else if guid.eq_ignore_ascii_case("{6D809377-6AF0-444B-8957-A3773F02200E}") {
        if let Some(root) = std::env::var_os("ProgramFiles") {
            candidates.push(PathBuf::from(root).join(relative));
        }
    } else {
        // Unknown folder GUID: probe the common install roots.
        for root in [
            std::env::var_os("ProgramFiles").map(PathBuf::from),
            std::env::var_os("ProgramFiles(x86)").map(PathBuf::from),
            std::env::var_os("LOCALAPPDATA").map(|p| PathBuf::from(p).join("Programs")),
            std::env::var_os("SystemRoot").map(|p| PathBuf::from(p).join("System32")),
        ]
        .into_iter()
        .flatten()
        {
            candidates.push(root.join(relative));
        }
    }
    candidates
        .into_iter()
        .find(|candidate| candidate.exists())
        .map(|candidate| candidate.to_string_lossy().into_owned())
}

/* ---------------- registry uninstall entries ---------------- */

const UNINSTALL_SUBKEY: &str = r"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall";
const APP_PATHS_SUBKEY: &str = r"SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths";

impl ScanCtx {
    fn scan_registry(&mut self) {
        for (hive, view) in [
            (HKEY_LOCAL_MACHINE, KEY_WOW64_64KEY),
            (HKEY_LOCAL_MACHINE, KEY_WOW64_32KEY),
            (HKEY_CURRENT_USER, KEY_WOW64_64KEY),
        ] {
            self.scan_uninstall_hive(hive, view);
        }
    }

    fn scan_uninstall_hive(&mut self, hive: HKEY, view: REG_SAM_FLAGS) {
        unsafe {
            let Ok(root) = open_key(hive, UNINSTALL_SUBKEY, view) else {
                return;
            };
            let mut index = 0u32;
            loop {
                let mut name_buf = [0u16; 512];
                let mut len = 512u32;
                let err = RegEnumKeyExW(
                    root,
                    index,
                    Some(PWSTR(name_buf.as_mut_ptr())),
                    &mut len,
                    None,
                    None,
                    None,
                    None,
                );
                if err.0 != 0 {
                    break;
                }
                index += 1;
                let key_name = String::from_utf16_lossy(&name_buf[..len as usize]);
                let Ok(subkey) = open_key(root, &key_name, KEY_READ) else {
                    continue;
                };
                self.index_registry_entry(subkey);
                let _ = RegCloseKey(subkey);
            }
            let _ = RegCloseKey(root);
        }
    }

    fn index_registry_entry(&mut self, hk: HKEY) {
        unsafe {
            let Some(name) = reg_string(hk, "DisplayName") else {
                return;
            };
            let name = name.trim().to_string();
            if name.is_empty() {
                return;
            }
            // Windows update / component bookkeeping, not launchable apps.
            if reg_dword(hk, "SystemComponent") == Some(1) {
                return;
            }
            if let Some(release_type) = reg_string(hk, "ReleaseType") {
                let lower = release_type.to_lowercase();
                if matches!(
                    lower.as_str(),
                    "security update"
                        | "update"
                        | "hotfix"
                        | "update rollup"
                        | "feature pack"
                        | "critical update"
                        | "service pack"
                ) {
                    return;
                }
            }
            if reg_string(hk, "ParentKeyName").is_some() {
                return;
            }
            let lower = name.to_lowercase();
            if lower.starts_with("kb")
                && lower.len() > 8
                && lower[2..].chars().all(|c| c.is_ascii_digit())
            {
                return;
            }
            if REGISTRY_SKIP_FRAGMENTS
                .iter()
                .any(|frag| lower.contains(frag))
            {
                return;
            }
            let display_icon = reg_string(hk, "DisplayIcon").unwrap_or_default();
            let install_location = reg_string(hk, "InstallLocation").unwrap_or_default();
            let display_icon = expand_env(&display_icon);
            let install_location = expand_env(&install_location);
            let exe = parse_icon_path(&display_icon).or_else(|| {
                if install_location.is_empty() {
                    None
                } else {
                    find_exe_in(&PathBuf::from(&install_location), &name)
                }
            });
            let Some(exe) = exe else {
                return;
            };
            if !exe
                .extension()
                .and_then(|e| e.to_str())
                .map(|e| e.eq_ignore_ascii_case("exe"))
                .unwrap_or(false)
            {
                return;
            }
            // Stale installs reference exes that no longer exist - drop them.
            if !exe.exists() {
                return;
            }
            let exe_str = exe.to_string_lossy().into_owned();
            let key = format!("{}|", exe_str.to_lowercase());
            if self.seen.contains_key(&key) {
                return;
            }
            let mut keywords = Vec::new();
            if let Some(stem) = exe.file_stem() {
                keywords.push(stem.to_string_lossy().into_owned());
            }
            if let Some(publisher) = reg_string(hk, "Publisher") {
                keywords.push(publisher);
            }
            if let Some(version) = reg_string(hk, "DisplayVersion") {
                keywords.push(version);
            }
            self.push(AppEntry {
                name: name.clone(),
                normalized_name: normalize(&name),
                app_id: key,
                icon: self.icons.get(&exe_str),
                path: Some(exe_str),
                args: None,
                working_directory: None,
                location: None,
                aumid: None,
                source: "registry".to_string(),
                keywords,
            });
        }
    }
}

/* ---------------- registered apps without shortcuts ---------------- */

impl ScanCtx {
    fn scan_registered_apps(&mut self) {
        for (hive, view) in [
            (HKEY_LOCAL_MACHINE, KEY_WOW64_64KEY),
            (HKEY_LOCAL_MACHINE, KEY_WOW64_32KEY),
            (HKEY_CURRENT_USER, KEY_WOW64_64KEY),
            (HKEY_CURRENT_USER, KEY_WOW64_32KEY),
        ] {
            self.scan_app_paths_hive(hive, view);
        }
        for view in [KEY_WOW64_64KEY, KEY_WOW64_32KEY] {
            self.scan_applications_registry(view);
        }
    }

    fn scan_app_paths_hive(&mut self, hive: HKEY, view: REG_SAM_FLAGS) {
        unsafe {
            let Ok(root) = open_key(hive, APP_PATHS_SUBKEY, view) else {
                return;
            };
            let mut index = 0u32;
            loop {
                let mut name_buf = [0u16; 512];
                let mut len = name_buf.len() as u32;
                let error = RegEnumKeyExW(
                    root,
                    index,
                    Some(PWSTR(name_buf.as_mut_ptr())),
                    &mut len,
                    None,
                    None,
                    None,
                    None,
                );
                if error.0 != 0 {
                    break;
                }
                index += 1;
                let key_name = String::from_utf16_lossy(&name_buf[..len as usize]);
                if !key_name.to_lowercase().ends_with(".exe") {
                    continue;
                }
                let Ok(key) = open_key(root, &key_name, KEY_READ) else {
                    continue;
                };
                let executable = reg_string(key, "")
                    .map(|value| expand_env(&value))
                    .and_then(|value| parse_registered_executable(&value));
                let _ = RegCloseKey(key);
                if let Some(executable) = executable {
                    self.index_registered_exe(executable, None, "appPaths", vec![key_name]);
                }
            }
            let _ = RegCloseKey(root);
        }
    }

    fn scan_applications_registry(&mut self, view: REG_SAM_FLAGS) {
        unsafe {
            let Ok(root) = open_key(HKEY_CLASSES_ROOT, "Applications", view) else {
                return;
            };
            let mut index = 0u32;
            loop {
                let mut name_buf = [0u16; 512];
                let mut len = name_buf.len() as u32;
                let error = RegEnumKeyExW(
                    root,
                    index,
                    Some(PWSTR(name_buf.as_mut_ptr())),
                    &mut len,
                    None,
                    None,
                    None,
                    None,
                );
                if error.0 != 0 {
                    break;
                }
                index += 1;
                let key_name = String::from_utf16_lossy(&name_buf[..len as usize]);
                if !key_name.to_lowercase().ends_with(".exe") {
                    continue;
                }
                let Ok(key) = open_key(root, &key_name, KEY_READ) else {
                    continue;
                };
                if reg_value_exists(key, "NoStartPage") || reg_value_exists(key, "IsHostApp") {
                    let _ = RegCloseKey(key);
                    continue;
                }
                let friendly_name = reg_string(key, "FriendlyAppName")
                    .filter(|name| !name.starts_with('@') && !name.trim().is_empty());
                let executable = open_key(key, r"shell\open\command", KEY_READ)
                    .ok()
                    .and_then(|command_key| {
                        let value = reg_string(command_key, "")
                            .map(|value| expand_env(&value))
                            .and_then(|value| parse_registered_executable(&value));
                        let _ = RegCloseKey(command_key);
                        value
                    });
                let _ = RegCloseKey(key);
                if let Some(executable) = executable {
                    self.index_registered_exe(
                        executable,
                        friendly_name,
                        "applications",
                        vec![key_name],
                    );
                }
            }
            let _ = RegCloseKey(root);
        }
    }

    fn index_registered_exe(
        &mut self,
        executable: PathBuf,
        friendly_name: Option<String>,
        source: &str,
        mut keywords: Vec<String>,
    ) {
        if !executable.is_file()
            || !executable
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("exe"))
        {
            return;
        }
        let Some(stem) = executable
            .file_stem()
            .map(|stem| stem.to_string_lossy().into_owned())
        else {
            return;
        };
        let lower_stem = stem.to_lowercase();
        if NOISE_STEMS
            .iter()
            .any(|noise| lower_stem.starts_with(noise))
        {
            return;
        }
        let path = executable.to_string_lossy().into_owned();
        let key = format!("{}|", path.to_lowercase());
        if self.seen.contains_key(&key) {
            return;
        }
        let name = friendly_name.unwrap_or_else(|| clean_name(&stem));
        if name.trim().is_empty() {
            return;
        }
        keywords.push(stem);
        if let Some(parent) = executable.parent().and_then(Path::file_name) {
            keywords.push(parent.to_string_lossy().into_owned());
        }
        self.push(AppEntry {
            name: name.clone(),
            normalized_name: normalize(&name),
            app_id: key,
            icon: self.icons.get(&path),
            path: Some(path),
            args: None,
            working_directory: None,
            location: None,
            aumid: None,
            source: source.to_string(),
            keywords,
        });
    }
}

/* ---------------- common executable locations ---------------- */

impl ScanCtx {
    fn scan_program_files(&mut self) {
        let mut roots = Vec::new();
        for fid in [FOLDERID_ProgramFiles, FOLDERID_ProgramFilesX86] {
            if let Some(dir) = unsafe { known_folder(&fid) } {
                roots.push(dir);
            }
        }
        if let Some(local) = unsafe { known_folder(&FOLDERID_LocalAppData) } {
            roots.push(local.join("Programs"));
        }
        for root in roots {
            let Ok(entries) = std::fs::read_dir(&root) else {
                continue;
            };
            let mut products = 0usize;
            for entry in entries.flatten() {
                if products >= 400 {
                    break;
                }
                let Ok(file_type) = entry.file_type() else {
                    continue;
                };
                if !file_type.is_dir() {
                    continue;
                }
                let product = entry.file_name().to_string_lossy().into_owned();
                if product.starts_with('.') || SKIP_DIRS.contains(&product.as_str()) {
                    continue;
                }
                products += 1;
                if let Some(exe) = pick_main_exe(&entry.path(), &product) {
                    self.index_exe(exe, &product);
                }
            }
        }
    }

    fn index_exe(&mut self, exe: PathBuf, product: &str) {
        let exe_str = exe.to_string_lossy().into_owned();
        let key = format!("{}|", exe_str.to_lowercase());
        if self.seen.contains_key(&key) {
            return;
        }
        let Some(stem) = exe.file_stem().map(|s| s.to_string_lossy().into_owned()) else {
            return;
        };
        if stem.is_empty() {
            return;
        }
        let name = clean_name(&stem);
        let mut keywords = vec![product.to_string(), stem];
        if let Some(parent) = exe.parent().and_then(|p| p.file_name()) {
            keywords.push(parent.to_string_lossy().into_owned());
        }
        self.push(AppEntry {
            name: name.clone(),
            normalized_name: normalize(&name),
            app_id: key,
            icon: self.icons.get(&exe_str),
            path: Some(exe_str),
            args: None,
            working_directory: None,
            location: None,
            aumid: None,
            source: "programs".to_string(),
            keywords,
        });
    }
}

/// Picks the "main" executable of an installed-product folder: the exe whose
/// stem matches the product folder name, else the largest exe near the root.
fn pick_main_exe(product_dir: &Path, product: &str) -> Option<PathBuf> {
    let product_lower = product.to_lowercase();
    let mut exact: Option<(u32, i64, PathBuf)> = None;
    let mut shallow: Option<(i64, PathBuf)> = None;
    let mut deep: Option<(i64, PathBuf)> = None;
    walk_exes(product_dir, 0, &mut 0, &mut |depth, path| {
        let stem = path
            .file_stem()
            .map(|s| s.to_string_lossy().to_lowercase())
            .unwrap_or_default();
        let size = path.metadata().map(|m| m.len() as i64).unwrap_or(0);
        if stem != product_lower && NOISE_STEMS.iter().any(|n| stem.starts_with(n)) {
            return;
        }
        if stem == product_lower {
            let better = exact
                .as_ref()
                .is_none_or(|(d, s, _)| depth < *d || (depth == *d && size > *s));
            if better {
                exact = Some((depth, size, path.to_path_buf()));
            }
        } else if depth <= 2 {
            if shallow.as_ref().is_none_or(|(s, _)| size > *s) {
                shallow = Some((size, path.to_path_buf()));
            }
        } else if deep.as_ref().is_none_or(|(s, _)| size > *s) {
            deep = Some((size, path.to_path_buf()));
        }
    });
    if let Some((_, _, path)) = exact {
        return Some(path);
    }
    if let Some((size, path)) = shallow {
        if size >= 64 * 1024 {
            return Some(path);
        }
    }
    if let Some((size, path)) = deep {
        if size >= 256 * 1024 {
            return Some(path);
        }
    }
    None
}

fn walk_exes(dir: &Path, depth: u32, count: &mut usize, on_file: &mut impl FnMut(u32, &Path)) {
    if depth > 3 || *count > 600 {
        return;
    }
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            if depth >= 3 {
                continue;
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            if matches!(name.as_str(), "node_modules" | ".git" | ".svn" | ".hg") {
                continue;
            }
            walk_exes(&entry.path(), depth + 1, count, on_file);
        } else if file_type.is_file() {
            let path = entry.path();
            let Some(ext) = path.extension() else {
                continue;
            };
            if ext.to_string_lossy().eq_ignore_ascii_case("exe") {
                *count += 1;
                on_file(depth, &path);
            }
        }
    }
}

/* ---------------- icons ---------------- */

struct IconCache {
    dir: PathBuf,
    /// Keys read or written by this scan. [`IconCache::prune`] deletes the
    /// rest: icons of removed apps and of app versions that were replaced.
    used: RefCell<HashSet<String>>,
}

impl IconCache {
    fn new(dir: PathBuf) -> Self {
        Self {
            dir,
            used: RefCell::new(HashSet::new()),
        }
    }

    /// Returns a PNG data-URL for a filesystem source (a path, .lnk or
    /// .url). Extracted PNGs are cached on disk so rescans are fast.
    fn get(&self, source: &str) -> Option<String> {
        self.get_for(source, &[], "")
    }

    /// `get` for an icon that also comes from other files (a shortcut's
    /// target and icon file) or from a package `version`. The key holds the
    /// stamp of each file, so an app updated in place gets a new key and its
    /// new icon is extracted.
    fn get_for(&self, source: &str, files: &[&str], version: &str) -> Option<String> {
        let mut key = format!("{source}|{version}");
        for file in std::iter::once(source).chain(files.iter().copied()) {
            key.push('|');
            key.push_str(&file_stamp(file));
        }
        self.load_or(&hash(&key), || unsafe { extract_file_icon(source) })
    }

    /// Same as `get`, but extraction is provided by the caller (used for
    /// virtual shell items that need their enumerated child PIDL). `key`
    /// must change when the icon can change.
    fn get_with(&self, key: &str, extract: impl FnOnce() -> Option<Vec<u8>>) -> Option<String> {
        self.load_or(&hash(key), extract)
    }

    fn load_or(&self, key: &str, extract: impl FnOnce() -> Option<Vec<u8>>) -> Option<String> {
        let png_path = self.dir.join(format!("{key}.png"));
        if let Ok(bytes) = std::fs::read(&png_path) {
            self.used.borrow_mut().insert(key.to_string());
            return Some(png_data_url(&bytes));
        }
        let png = extract()?;
        let _ = std::fs::create_dir_all(&self.dir);
        if std::fs::write(&png_path, &png).is_ok() {
            self.used.borrow_mut().insert(key.to_string());
        }
        Some(png_data_url(&png))
    }

    /// Deletes cached icons that this scan did not use. Call it only after a
    /// full scan.
    fn prune(&self) {
        let used = self.used.borrow();
        let Ok(entries) = std::fs::read_dir(&self.dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let stale = path
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("png"))
                && path
                    .file_stem()
                    .and_then(|stem| stem.to_str())
                    .is_some_and(|stem| !used.contains(stem));
            if stale {
                let _ = std::fs::remove_file(path);
            }
        }
    }
}

/// Size, modified time and created time of a file, or `-` when it is not a
/// file. Updaters that keep the build's modified time still write a new file,
/// which gets a new created time.
fn file_stamp(path: &str) -> String {
    if path.is_empty() {
        return "-".to_string();
    }
    let Ok(meta) = std::fs::metadata(path) else {
        return "-".to_string();
    };
    let nanos = |time: std::io::Result<SystemTime>| {
        time.ok()
            .and_then(|time| time.duration_since(SystemTime::UNIX_EPOCH).ok())
            .map_or(0, |elapsed| elapsed.as_nanos())
    };
    format!(
        "{}-{}-{}",
        meta.len(),
        nanos(meta.modified()),
        nanos(meta.created())
    )
}

const PACKAGE_REPOSITORY: &str =
    r"Software\Classes\Local Settings\Software\Microsoft\Windows\CurrentVersion\AppModel\Repository\Packages";

/// Installed package full names by package family. A package update
/// registers a new full name (`Name_Version_Arch_Resource_Publisher`).
struct PackageVersions {
    by_family: HashMap<String, String>,
}

impl PackageVersions {
    fn load() -> Self {
        let mut by_family: HashMap<String, Vec<String>> = HashMap::new();
        for full_name in unsafe { package_full_names() } {
            if let Some(family) = package_family(&full_name) {
                by_family.entry(family).or_default().push(full_name);
            }
        }
        Self {
            by_family: by_family
                .into_iter()
                .map(|(family, mut names)| {
                    names.sort();
                    (family, names.join(";"))
                })
                .collect(),
        }
    }

    /// The installed versions of the package an AUMID (`Family!App`) belongs
    /// to, or `""` for an unpackaged app.
    fn version(&self, aumid: &str) -> &str {
        aumid
            .split_once('!')
            .and_then(|(family, _)| self.by_family.get(&family.to_lowercase()))
            .map_or("", String::as_str)
    }
}

/// `Name_Publisher` from `Name_Version_Arch_Resource_Publisher`, lowercase.
fn package_family(full_name: &str) -> Option<String> {
    let parts = full_name.split('_').collect::<Vec<_>>();
    (parts.len() == 5).then(|| format!("{}_{}", parts[0], parts[4]).to_lowercase())
}

unsafe fn package_full_names() -> Vec<String> {
    let Some(key) = open_package_repository() else {
        return Vec::new();
    };
    let mut names = Vec::new();
    for index in 0.. {
        let mut buffer = [0u16; 256];
        let mut length = buffer.len() as u32;
        let result = RegEnumKeyExW(
            key,
            index,
            Some(PWSTR(buffer.as_mut_ptr())),
            &mut length,
            None,
            None,
            None,
            None,
        );
        if result.0 != 0 {
            break;
        }
        names.push(String::from_utf16_lossy(&buffer[..length as usize]));
    }
    let _ = RegCloseKey(key);
    names
}

unsafe fn open_package_repository() -> Option<HKEY> {
    let path = wide(PACKAGE_REPOSITORY);
    let mut key = HKEY::default();
    RegOpenKeyExW(
        HKEY_CURRENT_USER,
        PCWSTR(path.as_ptr()),
        None,
        KEY_READ,
        &mut key,
    )
    .is_ok()
    .then_some(key)
}

/// True when a package was installed, updated or removed after `since`:
/// each change adds or deletes a subkey of the package repository.
fn packages_changed_since(since: SystemTime) -> bool {
    unsafe {
        let Some(key) = open_package_repository() else {
            return false;
        };
        let mut written = FILETIME::default();
        let result = RegQueryInfoKeyW(
            key,
            None,
            None,
            None,
            None,
            None,
            None,
            None,
            None,
            None,
            None,
            Some(&mut written),
        );
        let _ = RegCloseKey(key);
        if result.0 != 0 {
            return false;
        }
        // FILETIME counts 100 ns intervals since 1601-01-01.
        let ticks = (u64::from(written.dwHighDateTime) << 32) | u64::from(written.dwLowDateTime);
        let unix_ticks = ticks.saturating_sub(116_444_736_000_000_000);
        SystemTime::UNIX_EPOCH + Duration::from_nanos(unix_ticks.saturating_mul(100)) > since
    }
}

/// The files of indexed apps whose change means an app was updated in place:
/// shortcuts and local executables. An update keeps the install folder, so
/// [`installs_changed_since`] does not see it.
pub fn watched_files(apps: &[AppEntry]) -> Vec<PathBuf> {
    let mut files = apps
        .iter()
        .flat_map(|app| [app.location.as_deref(), app.path.as_deref()])
        .flatten()
        .filter(|path| !path.contains("://") && Path::new(path).is_absolute())
        .map(PathBuf::from)
        .collect::<Vec<_>>();
    files.sort();
    files.dedup();
    files
}

/// True when an indexed app was updated after `since`: one of its `files`
/// (from [`watched_files`]) was written or replaced, or a package changed.
pub fn apps_updated_since(files: &[PathBuf], since: SystemTime) -> bool {
    files.iter().any(|path| written_after(path, since)) || packages_changed_since(since)
}

fn written_after(path: &Path, since: SystemTime) -> bool {
    std::fs::metadata(path).is_ok_and(|meta| {
        [meta.modified(), meta.created()]
            .into_iter()
            .flatten()
            .any(|time| time > since)
    })
}

/// Extracts an icon for a filesystem path (exe, ico, .lnk or .url) via
/// SHGetFileInfoW, which lets the shell resolve shortcut icons.
unsafe fn extract_file_icon(path: &str) -> Option<Vec<u8>> {
    use windows::Win32::Storage::FileSystem::FILE_FLAGS_AND_ATTRIBUTES;
    use windows::Win32::UI::Shell::{
        SHGetFileInfoW, SHFILEINFOW, SHGFI_FLAGS, SHGFI_ICON, SHGFI_LARGEICON,
    };
    use windows::Win32::UI::WindowsAndMessaging::DestroyIcon;

    let wide_path = wide(path);
    let mut info = std::mem::zeroed::<SHFILEINFOW>();
    let result = SHGetFileInfoW(
        PCWSTR(wide_path.as_ptr()),
        FILE_FLAGS_AND_ATTRIBUTES(0),
        Some(&mut info),
        std::mem::size_of::<SHFILEINFOW>() as u32,
        SHGFI_FLAGS(SHGFI_ICON.0 | SHGFI_LARGEICON.0),
    );
    if result == 0 || info.hIcon.0.is_null() {
        return None;
    }
    let png = hicon_to_png(info.hIcon);
    let _ = DestroyIcon(info.hIcon);
    png
}

/// Returns a PNG data URL for a shell item's native icon.
pub fn shell_item_icon_data_url(item: &IShellItem) -> Option<String> {
    unsafe { extract_shell_item_icon(item).map(|png| png_data_url(&png)) }
}

unsafe fn extract_shell_item_icon(item: &IShellItem) -> Option<Vec<u8>> {
    let factory = item.cast::<IShellItemImageFactory>().ok()?;
    let bitmap = factory
        .GetImage(SIZE { cx: 64, cy: 64 }, SIIGBF_ICONONLY)
        .ok()?;
    bitmap_to_png(bitmap)
}

/// Extracts an icon for a virtual AppsFolder item through the Shell image
/// factory. Modern AppX/MSIX apps expose their package logo this way rather
/// than as an icon resource filename. Older shell extensions fall back to
/// IExtractIconW below.
unsafe fn extract_apps_folder_icon(
    item: &IShellItem,
    folder: &IShellFolder,
    pidl: *mut ITEMIDLIST,
) -> Option<Vec<u8>> {
    extract_shell_item_icon(item).or_else(|| extract_legacy_apps_folder_icon(folder, pidl))
}

unsafe fn extract_legacy_apps_folder_icon(
    folder: &IShellFolder,
    pidl: *mut ITEMIDLIST,
) -> Option<Vec<u8>> {
    use windows::Win32::UI::Shell::{
        ExtractIconExW, IExtractIconW, GIL_FORSHELL, GIL_NOTFILENAME, GIL_OPENICON,
    };
    use windows::Win32::UI::WindowsAndMessaging::{DestroyIcon, HICON};

    let icon: IExtractIconW = folder
        .GetUIObjectOf(
            HWND(std::ptr::null_mut()),
            &[pidl as *const ITEMIDLIST],
            None,
        )
        .ok()?;
    let mut path_buf = [0u16; 260];
    let mut index = 0i32;
    let mut flags = 0u32;
    icon.GetIconLocation(
        GIL_OPENICON | GIL_FORSHELL,
        &mut path_buf,
        &mut index,
        &mut flags,
    )
    .ok()?;
    let path = wide_trim(&path_buf);
    let mut hicon = HICON(std::ptr::null_mut());
    // GIL_NOTFILENAME means pszIconFile is a resource spec, not a file.
    if flags & GIL_NOTFILENAME == 0 && !path.is_empty() {
        let wide_path = wide(&path);
        let count = ExtractIconExW(PCWSTR(wide_path.as_ptr()), index, Some(&mut hicon), None, 1);
        if count == 0 {
            hicon.0 = std::ptr::null_mut();
        }
    }
    if hicon.0.is_null() {
        let wide_path = wide(&path);
        icon.Extract(
            PCWSTR(wide_path.as_ptr()),
            index as u32,
            Some(&mut hicon),
            None,
            0,
        )
        .ok()?;
    }
    if hicon.0.is_null() {
        return None;
    }
    let png = hicon_to_png(hicon);
    let _ = DestroyIcon(hicon);
    png
}

/// Converts an HICON to PNG bytes: GetIconInfo gives the color bitmap,
/// which bitmap_to_png renders (BGRA -> RGBA with alpha handling).
unsafe fn hicon_to_png(icon: windows::Win32::UI::WindowsAndMessaging::HICON) -> Option<Vec<u8>> {
    use windows::Win32::Graphics::Gdi::HGDIOBJ;
    use windows::Win32::UI::WindowsAndMessaging::{GetIconInfo, ICONINFO};

    let mut info = std::mem::zeroed::<ICONINFO>();
    if GetIconInfo(icon, &mut info).is_err() {
        return None;
    }
    let color = info.hbmColor;
    let mask = info.hbmMask;
    let png = if !color.0.is_null() {
        bitmap_to_png(color)
    } else {
        // Monochrome icons carry no color bitmap; skip rather than render
        // a black square.
        let _ = DeleteObject(HGDIOBJ(mask.0));
        None
    };
    if !color.0.is_null() && !mask.0.is_null() {
        let _ = DeleteObject(HGDIOBJ(mask.0));
    }
    png
}

/// Converts an HBITMAP to PNG bytes (BGRA -> RGBA via GetDIBits, with
/// premultiplied-alpha and no-alpha handling). Always consumes the bitmap.
unsafe fn bitmap_to_png(bitmap: HBITMAP) -> Option<Vec<u8>> {
    let bitmap_handle = HGDIOBJ(bitmap.0);
    let mut bmp: BITMAP = std::mem::zeroed();
    let copied = GetObjectW(
        bitmap_handle,
        std::mem::size_of::<BITMAP>() as i32,
        Some(&mut bmp as *mut _ as *mut c_void),
    );
    if copied == 0 {
        let _ = DeleteObject(bitmap_handle);
        return None;
    }
    let width = bmp.bmWidth;
    let height = bmp.bmHeight;
    if width <= 0 || height <= 0 || width > 512 || height > 512 {
        let _ = DeleteObject(bitmap_handle);
        return None;
    }
    let screen = GetDC(None);
    let memory = CreateCompatibleDC(Some(screen));
    let old = SelectObject(memory, bitmap_handle);
    let mut info: BITMAPINFO = std::mem::zeroed();
    info.bmiHeader.biSize = std::mem::size_of::<BITMAPINFOHEADER>() as u32;
    info.bmiHeader.biWidth = width;
    info.bmiHeader.biHeight = -height; // top-down rows
    info.bmiHeader.biPlanes = 1;
    info.bmiHeader.biBitCount = 32;
    info.bmiHeader.biCompression = BI_RGB.0;
    let mut pixels = vec![0u8; width as usize * height as usize * 4];
    let lines = GetDIBits(
        memory,
        bitmap,
        0,
        height as u32,
        Some(pixels.as_mut_ptr() as *mut c_void),
        &mut info,
        DIB_RGB_COLORS,
    );
    let _ = SelectObject(memory, old);
    let _ = DeleteDC(memory);
    if !screen.is_invalid() {
        let _ = ReleaseDC(None, screen);
    }
    let _ = DeleteObject(bitmap_handle);
    if lines <= 0 {
        return None;
    }
    // GetDIBits yields BGRA; shell bitmaps arrive with premultiplied alpha.
    let has_alpha = pixels.as_chunks::<4>().0.iter().any(|p| p[3] != 0);
    if !has_alpha {
        // No alpha channel: the 32-bit conversion filled 0s - force opaque.
        for px in pixels.as_chunks_mut::<4>().0 {
            px[3] = 255;
        }
    } else {
        for px in pixels.as_chunks_mut::<4>().0 {
            let (b, g, r, a) = (px[0] as u32, px[1] as u32, px[2] as u32, px[3] as u32);
            let scale = |c: u32| ((c * 255) / a.max(1)).min(255) as u8;
            px[0] = scale(r);
            px[1] = scale(g);
            px[2] = scale(b);
        }
    }
    let image = image::RgbaImage::from_raw(width as u32, height as u32, pixels)?;
    let mut out = Cursor::new(Vec::new());
    image.write_to(&mut out, image::ImageFormat::Png).ok()?;
    Some(out.into_inner())
}

