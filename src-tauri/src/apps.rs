unsafe fn open_key(parent: HKEY, path: &str, access: REG_SAM_FLAGS) -> Result<HKEY, ()> {
    let wide_path = wide(path);
    let mut key = HKEY(std::ptr::null_mut());
    let err = RegOpenKeyExW(
        parent,
        PCWSTR(wide_path.as_ptr()),
        None,
        access | KEY_READ,
        &mut key,
    );
    if err.0 != 0 || key.0.is_null() {
        return Err(());
    }
    Ok(key)
}

/// Reads a REG_SZ / REG_EXPAND_SZ / REG_DWORD value as a string.
unsafe fn reg_string(hk: HKEY, name: &str) -> Option<String> {
    let wide_name = wide(name);
    let mut value_type = REG_VALUE_TYPE(0);
    let mut len = 0u32;
    let err = RegQueryValueExW(
        hk,
        PCWSTR(wide_name.as_ptr()),
        None,
        Some(&mut value_type),
        None,
        Some(&mut len),
    );
    if err.0 != 0 || len == 0 {
        return None;
    }
    let mut buf = vec![0u8; len as usize];
    let err = RegQueryValueExW(
        hk,
        PCWSTR(wide_name.as_ptr()),
        None,
        Some(&mut value_type),
        Some(buf.as_mut_ptr()),
        Some(&mut len),
    );
    if err.0 != 0 {
        return None;
    }
    if value_type.0 == REG_SZ.0 || value_type.0 == REG_EXPAND_SZ.0 {
        let units: Vec<u16> = buf
            .chunks_exact(2)
            .map(|c| u16::from_le_bytes([c[0], c[1]]))
            .collect();
        let end = units.iter().position(|&u| u == 0).unwrap_or(units.len());
        Some(String::from_utf16_lossy(&units[..end]).trim().to_string())
    } else if value_type.0 == REG_DWORD.0 {
        // Registry values are third-party data; guard the slice so a
        // malformed value length cannot panic the scan.
        let value = u32::from_le_bytes(buf.get(..4)?.try_into().ok()?);
        Some(value.to_string())
    } else {
        None
    }
}

/// Reports whether a registry value exists without depending on its type or
/// contents. Shell registrations use empty marker values such as NoStartPage.
unsafe fn reg_value_exists(hk: HKEY, name: &str) -> bool {
    let wide_name = wide(name);
    RegQueryValueExW(hk, PCWSTR(wide_name.as_ptr()), None, None, None, None).0 == 0
}

unsafe fn reg_dword(hk: HKEY, name: &str) -> Option<u32> {
    let wide_name = wide(name);
    let mut value_type = REG_VALUE_TYPE(0);
    let mut len = 4u32;
    let mut buf = [0u8; 4];
    let err = RegQueryValueExW(
        hk,
        PCWSTR(wide_name.as_ptr()),
        None,
        Some(&mut value_type),
        Some(buf.as_mut_ptr()),
        Some(&mut len),
    );
    if err.0 != 0 || value_type.0 != REG_DWORD.0 {
        return None;
    }
    Some(u32::from_le_bytes(buf))
}

/// Strips quotes and a trailing ",index" from a DisplayIcon value.
fn parse_icon_path(value: &str) -> Option<PathBuf> {
    let mut value = value.trim();
    if let Some((path, tail)) = value.rsplit_once(',') {
        if !tail.trim().is_empty() && tail.trim().parse::<i32>().is_ok() {
            value = path.trim();
        }
    }
    let value = value.trim_matches('"').trim();
    if value.is_empty() {
        return None;
    }
    Some(PathBuf::from(value))
}

/// Extracts the executable from an App Paths value or an Applications
/// `shell\open\command` registration. Registered commands may quote a path
/// containing spaces or append placeholders and command-line arguments.
fn parse_registered_executable(value: &str) -> Option<PathBuf> {
    let value = value.trim();
    if value.is_empty() {
        return None;
    }

    let executable = if let Some(quoted) = value.strip_prefix('"') {
        let end = quoted.find('"')?;
        &quoted[..end]
    } else {
        let lower = value.to_ascii_lowercase();
        let end = lower.find(".exe")? + ".exe".len();
        &value[..end]
    };
    let executable = executable.trim();
    (!executable.is_empty()).then(|| PathBuf::from(executable))
}

/// Finds the launcher exe inside an install folder: prefer one whose stem
/// appears in the display name, else the largest exe at the root.
fn find_exe_in(dir: &Path, display_name: &str) -> Option<PathBuf> {
    let name_lower = display_name.to_lowercase();
    let mut best: Option<(i64, PathBuf)> = None;
    for entry in std::fs::read_dir(dir).ok()?.flatten() {
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if !file_type.is_file() {
            continue;
        }
        let path = entry.path();
        let is_exe = path
            .extension()
            .and_then(|e| e.to_str())
            .map(|e| e.eq_ignore_ascii_case("exe"))
            .unwrap_or(false);
        if !is_exe {
            continue;
        }
        let stem = path
            .file_stem()
            .map(|s| s.to_string_lossy().to_lowercase())
            .unwrap_or_default();
        if !stem.is_empty() && name_lower.contains(&stem) {
            return Some(path);
        }
        let size = path.metadata().map(|m| m.len() as i64).unwrap_or(0);
        if best.as_ref().is_none_or(|(s, _)| size > *s) {
            best = Some((size, path));
        }
    }
    best.filter(|(size, _)| *size >= 64 * 1024)
        .map(|(_, path)| path)
}

/* ---------------- string helpers ---------------- */

fn wide(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(std::iter::once(0)).collect()
}

unsafe fn read_buf16(f: impl FnOnce(&mut [u16]) -> windows::core::Result<()>) -> String {
    let mut buf = [0u16; 2048];
    if f(&mut buf).is_ok() {
        wide_trim(&buf)
    } else {
        String::new()
    }
}

fn wide_trim(buf: &[u16]) -> String {
    let end = buf.iter().position(|&c| c == 0).unwrap_or(buf.len());
    String::from_utf16_lossy(&buf[..end]).trim().to_string()
}

fn clean_name(stem: &str) -> String {
    let mut name = stem.trim().to_string();
    for suffix in [" - Shortcut", " (2)", " (3)"] {
        if let Some(stripped) = name.strip_suffix(suffix) {
            name = stripped.trim().to_string();
        }
    }
    name
}

/// Expands %VAR% references using the process environment.
fn expand_env(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let chars: Vec<char> = value.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '%' {
            if let Some(end) = chars[i + 1..].iter().position(|&c| c == '%') {
                let name: String = chars[i + 1..i + 1 + end].iter().collect();
                if let Ok(v) = std::env::var(&name) {
                    out.push_str(&v);
                    i += end + 2;
                    continue;
                }
            }
        }
        out.push(chars[i]);
        i += 1;
    }
    out
}

/// Lowercased alphanumerics only, for punctuation-insensitive exact match.
fn normalize(name: &str) -> String {
    name.to_lowercase()
        .chars()
        .filter(|c| c.is_alphanumeric())
        .collect()
}

fn dedupe_keywords(keywords: Vec<String>) -> Vec<String> {
    let mut seen: HashMap<String, ()> = HashMap::new();
    keywords
        .into_iter()
        .filter_map(|kw| {
            let normalized = kw.to_lowercase();
            if normalized.trim().is_empty() {
                return None;
            }
            if seen.insert(normalized.clone(), ()).is_some() {
                return None;
            }
            Some(normalized)
        })
        .collect()
}

fn looks_virtual(target: &str) -> bool {
    let lower = target.to_lowercase();
    lower.starts_with("shell:") || lower.contains("::{")
}

fn hash(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for byte in s.bytes() {
        h ^= byte as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn png_data_url(bytes: &[u8]) -> String {
    const TABLE: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        out.push(TABLE[(b[0] >> 2) as usize] as char);
        out.push(TABLE[((b[0] & 0x03) << 4 | b[1] >> 4) as usize] as char);
        out.push(if chunk.len() > 1 {
            TABLE[((b[1] & 0x0f) << 2 | b[2] >> 6) as usize] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            TABLE[(b[2] & 0x3f) as usize] as char
        } else {
            '='
        });
    }
    format!("data:image/png;base64,{out}")
}

unsafe fn known_folder(id: &GUID) -> Option<PathBuf> {
    let path = SHGetKnownFolderPath(id, Default::default(), None).ok()?;
    let text = path.to_string().unwrap_or_default();
    CoTaskMemFree(Some(path.as_ptr() as *const c_void));
    if text.is_empty() {
        None
    } else {
        Some(PathBuf::from(text))
    }
}

fn icon_cache_dir() -> PathBuf {
    unsafe {
        if let Some(appdata) = known_folder(&FOLDERID_RoamingAppData) {
            return appdata.join("app.prism.launcher").join("icons");
        }
    }
    PathBuf::from(".")
}

/// Reads a VT_LPWSTR out of a PROPVARIANT (windows-rs 0.61 exposes the raw
/// union rather than helpers).
unsafe fn prop_lpwstr(value: &PROPVARIANT) -> Option<String> {
    let inner = &value.Anonymous.Anonymous;
    if inner.vt == VT_LPWSTR {
        let ptr = inner.Anonymous.pwszVal;
        if !ptr.is_null() {
            return Some(ptr.to_string().unwrap_or_default());
        }
    }
    None
}

/* ---------------- launch ---------------- */

/// Launches an app the way the real Start menu would: shortcut-backed
/// entries run through their .lnk/.url (so the shell applies the working
/// directory, arguments and environment exactly as authored), packaged apps
/// go through shell:AppsFolder by AUMID, everything else runs the resolved
/// target directly.
pub fn launch(app: &AppEntry) -> Result<(), String> {
    unsafe {
        if let Some(path) = app.path.as_deref().filter(|path| is_executable(path)) {
            if shell_open(path, app.args.as_deref(), app.working_directory.as_deref()) {
                return Ok(());
            }
        }
        if let Some(location) = &app.location {
            if !location.is_empty()
                && Path::new(location).exists()
                && shell_open(location, None, None)
            {
                return Ok(());
            }
        }
        if let Some(aumid) = &app.aumid {
            if activate_packaged_app(aumid).is_ok() {
                return Ok(());
            }
            return explorer_arg(&format!("shell:AppsFolder\\{aumid}"));
        }
        if let Some(path) = &app.path {
            if !path.is_empty()
                && shell_open(path, app.args.as_deref(), app.working_directory.as_deref())
            {
                return Ok(());
            }
        }
        Err(format!("failed to launch {}", app.name))
    }
}

/// Launches a scanned desktop application or script through Windows' `runas`
/// verb. Packaged apps have no local process target and are intentionally not
/// eligible for elevation.
pub fn launch_elevated(app: &AppEntry) -> Result<(), String> {
    let path = app
        .path
        .as_deref()
        .map(Path::new)
        .filter(|path| path.is_absolute() && path.is_file())
        .ok_or_else(|| format!("{} cannot be run as administrator", app.name))?;
    launch_path_elevated(path, app.args.as_deref(), app.working_directory.as_deref())
}

pub fn launch_path_elevated(
    path: &Path,
    args: Option<&str>,
    working_directory: Option<&str>,
) -> Result<(), String> {
    if !path.is_file() || !is_elevatable_path(path) {
        return Err(format!(
            "{} is not a supported application or script",
            path.display()
        ));
    }

    let path_text = path.to_string_lossy();
    let extension = path
        .extension()
        .and_then(|value| value.to_str())
        .unwrap_or_default()
        .to_ascii_lowercase();
    let fallback_directory = path.parent().map(|parent| parent.to_string_lossy());
    let directory = working_directory
        .filter(|value| !value.is_empty())
        .or(fallback_directory.as_deref());
    let (target, parameters) = elevated_command(&path_text, &extension, args);

    unsafe { shell_execute("runas", &target, parameters.as_deref(), directory) }.map_err(|code| {
        if code == 5 {
            "Administrator permission was not granted".to_string()
        } else {
            format!(
                "failed to run {} as administrator (Shell error {code})",
                path.display()
            )
        }
    })
}

pub fn is_elevatable_path(path: &Path) -> bool {
    path.extension()
        .and_then(|value| value.to_str())
        .is_some_and(|extension| {
            matches!(
                extension.to_ascii_lowercase().as_str(),
                "exe" | "com" | "bat" | "cmd" | "ps1" | "vbs" | "js" | "wsf"
            )
        })
}

fn elevated_command(path: &str, extension: &str, args: Option<&str>) -> (String, Option<String>) {
    let trailing_args = args
        .filter(|value| !value.trim().is_empty())
        .map(|value| format!(" {value}"))
        .unwrap_or_default();
    match extension {
        "bat" | "cmd" => (
            "cmd.exe".to_string(),
            Some(format!("/d /s /c \"\"{path}\"{trailing_args}\"")),
        ),
        "ps1" => (
            "powershell.exe".to_string(),
            Some(format!(
                "-NoLogo -NoProfile -File \"{path}\"{trailing_args}"
            )),
        ),
        "vbs" | "js" | "wsf" => (
            "wscript.exe".to_string(),
            Some(format!("//nologo \"{path}\"{trailing_args}")),
        ),
        _ => (path.to_string(), args.map(str::to_string)),
    }
}

fn activate_packaged_app(aumid: &str) -> Result<(), String> {
    let _com = ComGuard::init();
    unsafe {
        let manager: IApplicationActivationManager =
            CoCreateInstance(&ApplicationActivationManager, None, CLSCTX_LOCAL_SERVER)
                .map_err(|error| format!("failed to create app activation manager: {error}"))?;
        let app_id = wide(aumid);
        manager
            .ActivateApplication(PCWSTR(app_id.as_ptr()), PCWSTR::null(), AO_NONE)
            .map(|_| ())
            .map_err(|error| format!("failed to activate {aumid}: {error}"))
    }
}

pub fn open_path(path: &Path) -> Result<(), String> {
    let value = path.to_string_lossy();
    if unsafe { shell_open(&value, None, None) } {
        Ok(())
    } else {
        Err(format!("failed to open {}", path.display()))
    }
}

pub fn open_path_location(path: &Path) -> Result<(), String> {
    let value = path.to_string_lossy();
    let arg = format!("/select,\"{value}\"");
    explorer_arg(&arg)
}

fn is_executable(path: &str) -> bool {
    Path::new(path)
        .extension()
        .is_some_and(|extension| extension.eq_ignore_ascii_case("exe"))
        && Path::new(path).is_file()
}

unsafe fn shell_open(path: &str, args: Option<&str>, working_directory: Option<&str>) -> bool {
    shell_execute("open", path, args, working_directory).is_ok()
}

unsafe fn shell_execute(
    operation: &str,
    path: &str,
    args: Option<&str>,
    working_directory: Option<&str>,
) -> Result<(), isize> {
    let file = wide(path);
    let operation = wide(operation);
    let params = args.map(wide);
    let directory = working_directory
        .filter(|value| !value.is_empty())
        .map(wide);
    let result = ShellExecuteW(
        None,
        Some(&PCWSTR(operation.as_ptr())),
        PCWSTR(file.as_ptr()),
        params.as_deref().map(|v| PCWSTR(v.as_ptr())).as_ref(),
        directory
            .as_deref()
            .map(|value| PCWSTR(value.as_ptr()))
            .as_ref(),
        SW_SHOWNORMAL,
    );
    // HINSTANCE values > 32 mean success; lower values are Shell error codes.
    let code = result.0 as isize;
    if code > 32 {
        Ok(())
    } else {
        Err(code)
    }
}

fn explorer_arg(arg: &str) -> Result<(), String> {
    Command::new("explorer.exe")
        .arg(arg)
        .spawn()
        .map(|_| ())
        .map_err(|e| format!("failed to launch: {e}"))
}

