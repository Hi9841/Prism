const CACHE_TTL: Duration = Duration::from_secs(6 * 60 * 60);
/// Bump when the scan output format changes so stale caches rescan.
const APPS_CACHE_VERSION: u32 = 7;

/// CLSID_ShellLink (not generated by windows-rs).
const CLSID_SHELL_LINK: GUID = GUID::from_u128(0x00021401_0000_0000_c000_000000000046);

/// Directories that are never worth scanning (huge, system or cache dirs).
const SKIP_DIRS: &[&str] = &[
    "node_modules",
    ".git",
    ".svn",
    ".hg",
    ".cache",
    "Windows",
    "WindowsApps",
    "ModifiableWindowsApps",
    "Windows Kits",
    "Microsoft SDKs",
    "Common Files",
    "Windows Defender",
];

